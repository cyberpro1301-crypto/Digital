export type TranslationKey = keyof typeof translations.en;

export function getInitialLang(): Lang {
  const saved = localStorage.getItem('dv-lang') as Lang | null;
  if (saved === 'en' || saved === 'ru') return saved;
  const browser = navigator.language.toLowerCase();
  return browser.startsWith('ru') ? 'ru' : 'en';
}

export function t(lang: Lang, key: TranslationKey, params?: Record<string, string | number>): string {
  let str = translations[lang][key] || translations.en[key] || key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      str = str.replace(`{${k}}`, String(v));
    }
  }
  return str;
}

export function formatCurrency(amount: number, lang: Lang): string {
  return new Intl.NumberFormat(lang === 'ru' ? 'ru-RU' : 'en-US', {
    style: 'currency',
    currency: 'USD',
    minimumFractionDigits: 2,
  }).format(amount);
}
